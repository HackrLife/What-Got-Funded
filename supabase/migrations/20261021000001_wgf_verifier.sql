-- Verifier agent (n8n section 3): one row per check of a round.
create table if not exists wgf.round_checks (
  id bigserial primary key,
  round_id bigint not null references wgf.rounds(id),
  checker text not null,                 -- 'gemini', 'claude', 'audit'
  model text,
  day date,                              -- the day the round was checked against
  verdict text not null check (verdict in ('ON_DAY', 'EARLIER', 'LATER', 'NOT_A_ROUND', 'NOT_FOUND', 'ERROR')),
  earliest_date date,
  earliest_url text,
  is_equity_round boolean,
  confidence numeric,
  notes text,
  dry_run boolean not null default false,
  raw jsonb,
  created_at timestamptz not null default now()
);
create index if not exists round_checks_round on wgf.round_checks (round_id, created_at desc);

